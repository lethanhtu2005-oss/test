export function byCategory(cat) {
  return cat ? catalog.filter((x) => x.cat === cat) : catalog;
}

export function getItem(id) {
  if (!id) return null;
  const resolvedId = ALIASES[id] || id;
  const item = catalog.find((x) => x.id === resolvedId) || null;
  if (item && ALIASES[id]) {
    return { ...item, id };
  }
  return item;
}

