export const OLD_QUARTER_BOUNDS = {
  minLat: 21.0250,
  maxLat: 21.0400,
  minLng: 105.8450,
  maxLng: 105.8600,
};

export function isWithinOldQuarter(lat, lng) {
  if (typeof lat !== "number" || typeof lng !== "number") return false;
  return (
    lat >= OLD_QUARTER_BOUNDS.minLat &&
    lat <= OLD_QUARTER_BOUNDS.maxLat &&
    lng >= OLD_QUARTER_BOUNDS.minLng &&
    lng <= OLD_QUARTER_BOUNDS.maxLng
  );
}

